"""Write a Boolean polynomial system in msolve and Magma input syntax (E04 task 6, E10).

A system here is the repository's canonical Boolean representation: a list of polynomials, each a
`set` of monomials, each monomial a `frozenset` of variable indices (the empty frozenset is the
constant 1).  That is what `legacy/aim3_macaulay.build_aim3`, `E06.build_kernel_model` and
`E12.build_first_layer` all produce.

Two consumers, two conventions:

* **msolve** works in F_p[x_1..x_N], not in a Boolean quotient ring, so the field equations
  `x_i^2 + x_i` must be part of the system.  `-v 2` then prints one line per F4 step, from which
  `parse_msolve_log` extracts the step degrees.
* **Magma** has a native `BooleanPolynomialRing`, where `x_i^2 = x_i` holds by construction and the
  field equations must NOT be added (they are 0).  The emitted file defines `nvars`, `sysname` and
  `MONS` (the monomial-index lists, 1-based) but *not* the ring: the driver
  `experiments/E04_full_system_hilbert/magma/aim3_f4_degrees.m` builds the ring so that the same
  exported system can be run under several monomial orders (E10 block orders).

Both writers emit the variables in the repository's index order (`x0` is variable 0), so a solution
vector can be compared position by position with `sol` from the builders.
"""
from __future__ import annotations

import json
import os
import re

__all__ = ["write_msolve", "write_magma", "write_system", "parse_msolve_log", "parse_magma_log",
           "system_stats"]


def _sorted_monomials(poly):
    """Monomials of one polynomial, deterministic order: by degree, then lexicographic."""
    return sorted((tuple(sorted(m)) for m in poly), key=lambda m: (len(m), m))


def system_stats(eqs, nv):
    degs = [max((len(m) for m in f), default=0) for f in eqs]
    return dict(nvars=nv, neqs=len(eqs), max_degree=max(degs) if degs else 0,
                terms=sum(len(f) for f in eqs),
                terms_per_eq=round(sum(len(f) for f in eqs) / max(len(eqs), 1), 2))


# ------------------------------------------------------------------------------------ msolve
def write_msolve(eqs, nv, path, field_equations=True, varname="x"):
    """msolve input: variable list, characteristic, then the polynomials separated by commas."""
    names = [f"{varname}{i}" for i in range(nv)]
    terms_written = 0
    with open(path, "w") as fh:
        fh.write(",".join(names) + "\n")
        fh.write("2\n")
        chunks = []
        for f in eqs:
            ms = _sorted_monomials(f)
            if not ms:
                continue                       # the zero polynomial carries no information
            chunks.append("+".join("1" if not m else "*".join(names[i] for i in m) for m in ms))
            terms_written += len(ms)
        if field_equations:
            # msolve is not in a Boolean ring: x^2 = x has to be imposed explicitly
            chunks += [f"{names[i]}^2+{names[i]}" for i in range(nv)]
        fh.write(",\n".join(chunks) + "\n")
    return dict(path=os.path.abspath(path), polynomials=len(chunks), terms=terms_written,
                field_equations=field_equations)


# ------------------------------------------------------------------------------------- Magma
def write_magma(eqs, nv, path, sysname="sys", extra=None):
    """Magma input: `nvars`, `sysname` and `MONS`, a sequence of monomial-index sequences (1-based).

    The ring is deliberately NOT created here -- `aim3_f4_degrees.m` builds it, so the same file can
    be run under grevlex and under the block orders of E10 without being regenerated.
    """
    with open(path, "w") as fh:
        fh.write("// generated by src/aim3/polysys_export.py -- do not edit\n")
        fh.write(f"nvars := {nv};\n")
        fh.write(f'sysname := "{sysname}";\n')
        for k, v in (extra or {}).items():
            fh.write(f"{k} := {json.dumps(v) if isinstance(v, str) else v};\n")
        fh.write("// MONS[i][j] = the variable indices (1-based) of monomial j of polynomial i;\n")
        fh.write("// the empty sequence is the constant 1.\n")
        fh.write("MONS := [\n")
        body = []
        for f in eqs:
            ms = _sorted_monomials(f)
            if not ms:
                continue
            body.append("[" + ",".join("[" + ",".join(str(i + 1) for i in m) + "]" for m in ms) + "]")
        fh.write(",\n".join(body))
        fh.write("\n];\n")
    return dict(path=os.path.abspath(path), polynomials=len(body))


def write_system(eqs, nv, outdir, tag, sysname=None, sol=None, meta=None):
    """Write `<tag>.ms`, `<tag>.magma.m` and `<tag>.json` (shape + provenance + planted solution)."""
    os.makedirs(outdir, exist_ok=True)
    ms = write_msolve(eqs, nv, os.path.join(outdir, tag + ".ms"))
    mg = write_magma(eqs, nv, os.path.join(outdir, tag + ".magma.m"), sysname=sysname or tag)
    info = dict(tag=tag, **system_stats(eqs, nv), msolve=ms, magma=mg)
    if sol is not None:
        info["solution"] = "".join(str(b) for b in sol)
    if meta:
        info.update(meta)
    with open(os.path.join(outdir, tag + ".json"), "w") as fh:
        json.dump(info, fh, indent=1, sort_keys=True)
    return info


# --------------------------------------------------------------------------------- log parsing
# msolve -v 2 prints a fixed-width table, one line per F4 round:
#     deg     sel   pairs        mat          density     new data     time(rd)
#       3     540     540    1827 x 2003        1.98%     372 new  168 zero   0.06 | 0.51
# Only lines with that exact five-number prefix are steps -- the summary block also contains
# "max. matrix data 3804 x 1796", which must NOT be counted as a round.
_MSOLVE_STEP = re.compile(r"^\s*(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s*x\s*(\d+)\s+[\d.]+%")


def parse_msolve_log(text):
    """-> dict(d_solv, steps=[(degree, rows, cols)...]) from an `msolve -v 2` log."""
    steps = []
    for line in text.splitlines():
        m = _MSOLVE_STEP.match(line)
        if not m:
            continue
        steps.append((int(m.group(1)), int(m.group(4)), int(m.group(5))))
    return dict(d_solv=max((d for d, _, _ in steps), default=None),
                max_rows=max((r for _, r, _ in steps), default=None),
                max_cols=max((c for _, _, c in steps), default=None),
                nsteps=len(steps), steps=steps)


# Magma's SetVerbose("Faugere", 2) prints, per step,
#     Basis length: 63, queue length: 212, step degree: 2, num pairs: 49
#     ...
#     Matrix size: 63 by 232
# so the step degree comes first and the matrix size belongs to the step that precedes it.
# "Degree counts: ..." lines must not be mistaken for a step degree.
_MAGMA_STEP = re.compile(r"step degree:\s*(\d+)")
_MAGMA_SIZE = re.compile(r"Matrix size:\s*(\d+)\s+by\s+(\d+)")


def parse_magma_log(text):
    """-> dict(d_solv, steps=[(degree, rows, cols)...]) from a Magma Faugere verbose log."""
    steps = []
    cur = None
    for line in text.splitlines():
        d = _MAGMA_STEP.search(line)
        if d:
            if cur is not None:
                steps.append(cur)
            cur = (int(d.group(1)), None, None)
            continue
        s = _MAGMA_SIZE.search(line)
        if s and cur is not None and cur[1] is None:
            cur = (cur[0], int(s.group(1)), int(s.group(2)))
    if cur is not None:
        steps.append(cur)
    return dict(d_solv=max((d for d, _, _ in steps), default=None),
                max_rows=max((r for _, r, _ in steps if r), default=None),
                max_cols=max((c for _, _, c in steps if c), default=None),
                nsteps=len(steps), steps=steps)
