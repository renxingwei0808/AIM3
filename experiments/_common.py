"""Import shim + reproducibility helpers shared by every experiment script.

* makes `legacy/*` and `src/aim3` importable from any experiment directory;
* `record()` appends a CSV row to `results/` with the provenance columns that
  CLAUDE.md ground rule 2 requires: `tier, host, commit, seconds` (+ `censored`).
"""
import os, sys, csv, platform, subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
for p in (os.path.join(ROOT, "legacy"), os.path.join(ROOT, "src")):
    if p not in sys.path:
        sys.path.insert(0, p)
# legacy/aim3_lab.CONWAY stops at n=16; this adds the (verified irreducible) moduli for n=17..24
# from src/aim3/gf2n.TOY_MODULI without touching legacy/ (CLAUDE.md rule 3).
import aim3.legacy_fields                                                          # noqa: E402,F401

# Set AIM3_RESULTS to send CSV rows somewhere else -- scripts/smoke_test.sh uses it so that a smoke
# run does not append throw-away rows to the committed tables.
RESULTS = os.environ.get("AIM3_RESULTS") or os.path.join(ROOT, "results")

# provenance columns appended to every row, in this order
PROVENANCE = ("tier", "host", "commit", "seconds", "censored")

HOST = platform.node() or "unknown"


def _git_commit():
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                             capture_output=True, text=True, timeout=10)
        if out.returncode == 0:
            return out.stdout.strip()
    except Exception:
        pass
    return "unknown"


COMMIT = _git_commit()


def record(csv_name, row, seconds=None, censored=0, tier="A", reset=False):
    """Append `row` (a dict) to results/<csv_name>, adding the provenance columns.

    `censored=1` marks a run that hit its time/memory budget: the numbers in the row
    are then LOWER BOUNDS, never values (CLAUDE.md ground rule 4).
    `reset=True` truncates the file first (for scripts that regenerate a whole table).
    Returns the absolute path written.
    """
    os.makedirs(RESULTS, exist_ok=True)
    path = os.path.join(RESULTS, csv_name)
    out = dict(row)
    out.setdefault("tier", tier)
    out.setdefault("host", HOST)
    out.setdefault("commit", COMMIT)
    if seconds is not None:
        out["seconds"] = round(float(seconds), 3)
    out.setdefault("seconds", "")
    out.setdefault("censored", int(censored))
    fields = [k for k in out if k not in PROVENANCE] + list(PROVENANCE)

    if reset and os.path.exists(path):
        os.remove(path)
    header = None
    if os.path.exists(path) and os.path.getsize(path) > 0:
        with open(path, newline="") as f:
            header = next(csv.reader(f), None)
    if header is not None:
        if set(header) != set(fields):
            raise ValueError(
                f"{csv_name}: existing header {header} does not match the row keys {fields}. "
                f"Delete the file (it is regenerated by the script) or fix the row.")
        fields = header
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        if header is None:
            w.writeheader()
        w.writerow(out)
    return path


def record_table(csv_name, rows, seconds=None, censored=0, tier="A"):
    """Regenerate results/<csv_name> from scratch with `rows` (list of dicts)."""
    path = None
    for i, r in enumerate(rows):
        path = record(csv_name, r, seconds=seconds, censored=censored, tier=tier, reset=(i == 0))
    return path
